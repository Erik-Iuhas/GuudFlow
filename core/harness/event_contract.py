"""The run-event contract shared by the backend and Studio (plan §12.2, O21).

Studio receives every board signal over the run websocket as
`{"type": "signal", "signal": {...}}` (shape: `worker.job_runner.serialise_signal`).
Most harness signals carry a JSON `detail`. This module is the single source of
truth for those detail shapes; `scripts/gen_studio_events.py` turns it (plus
`core.signals.SignalType`) into `studio/src/lib/runEvents.gen.ts`, and
`tests/harness/test_event_contract.py` checks real emitted payloads against it.

Field types are TypeScript type expressions; a trailing `?` on a field name
marks it optional.
"""

from __future__ import annotations

# Signal type → {field: TS type}. Only kinds whose `detail` is JSON are listed.
