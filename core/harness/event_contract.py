ENUMS: dict[str, tuple[str, ...]] = {
    "TaskColumn": ("todo", "in_progress", "review", "done", "blocked", "needs_attention"),
    "ThreadKind": ("note", "blocked_on", "review_issue", "decision", "intervention",
                   "human_comment", "artifact", "handoff"),
    "InterventionType": ("rebrief", "decide", "reassign", "split", "extend_review",
                         "restart_role", "pause", "propose_team_change"),
}


def required_fields(kind: str) -> set[str]:
    """Fields every `kind` detail must carry."""
    return {f for f in DETAIL_SHAPES.get(kind, {}) if not f.endswith("?")}


def known_fields(kind: str) -> set[str]:
    """Every field the contract knows for `kind`."""
    return {f.rstrip("?") for f in DETAIL_SHAPES.get(kind, {})}


def render_typescript(signal_types: list[str]) -> str:
    """The generated TypeScript module (studio/src/lib/runEvents.gen.ts)."""
    out = ["// GENERATED by scripts/gen_studio_events.py from core/signals.py and",
           "// core/harness/event_contract.py. Do not edit by hand.", ""]
    out.append("export type SignalType =\n" + "\n".join(f"  | \"{t}\"" for t in signal_types)
               + ";\n")
    for name, values in ENUMS.items():
        out.append(f"export type {name} = " + " | ".join(f"\"{v}\"" for v in values) + ";\n")
    out.append("export interface RawSignal {\n  id: string;\n  type: SignalType;\n"
               "  summary: string;\n  detail: string | null;\n  from_agent: string | null;\n"
               "  from_user?: boolean;\n  priority: \"normal\" | \"high\";\n"
               "  iteration: number;\n  seen_by?: string[];\n  timestamp: string;\n}\n")
    names = []
    for kind, fields in DETAIL_SHAPES.items():
        iface = "".join(part.capitalize() for part in kind.lower().split("_")) + "Detail"
        names.append((kind, iface))
        body = "\n".join(f"  {field}: {ts};" for field, ts in fields.items())
        out.append(f"export interface {iface} {{\n{body}\n}}\n")
    out.append("export interface DetailByType {\n"
               + "\n".join(f"  {kind}: {iface};" for kind, iface in names) + "\n}\n")
    out.append("export type TypedSignal = {\n  [K in SignalType]: RawSignal & {\n    type: K;\n"
               "    data: K extends keyof DetailByType ? DetailByType[K] | null : null;\n  };\n"
               "}[SignalType];\n")
    out.append("export const JSON_DETAIL_TYPES: ReadonlySet<SignalType> = new Set([\n"
               + "\n".join(f"  \"{kind}\"," for kind in DETAIL_SHAPES) + "\n]);\n")
    return "\n".join(out)
