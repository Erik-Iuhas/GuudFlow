"""The project knowledge base (role contracts plan §4.3): what the team knows about its code.

Three layers, kept apart because they are trusted differently:

1. **Facts** (`build_facts`): generated by GuudFlow from the project repo's `main`, never by a
   model: each code module with its size, exported names and owning design component; the test
   files; which tests verified which checks (from the last accepted sessions' ledgers); the check
   command that works. Rebuilt after every accepted session; stored in
   `projects/{id}/knowledge/facts.json`.
2. **Notes** (`KnowledgeNote`, `add_notes`): conventions, gotchas and how-tos a role proposes
   (the tech lead promotes what more than one role needs from the session notebooks). Approved
   by the tech lead when no human holds the Lead seat, otherwise by the Lead. A note whose paths
   change in an accepted session turns `stale` until someone confirms or replaces it.
3. **History**: the record (`core/record.py`), unchanged.

Card briefs get the facts and approved notes for the card's files (`render_for_brief`). Notes a
person approved are trusted; notes only an agent approved are wrapped as untrusted content.
"""
from __future__ import annotations

import json
import subprocess
import time
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field

from core.design import Design, path_matches
from core.harness.brief import wrap_untrusted
from core.harness.handoff import exported_names
from core.work_db import WorkDB

FACTS_FILE = "facts.json"
CODE_SUFFIXES = (".py", ".js", ".mjs", ".cjs", ".ts", ".tsx", ".jsx")
SKIP_PARTS = ("node_modules/", ".guudflow/", "dist/", "build/", ".git/", "__pycache__/")
MAX_MODULES = 400
MAX_FACT_LINES = 25

NoteStatus = Literal["proposed", "approved", "stale", "dropped"]


class KnowledgeNote(BaseModel):
    """A note a role proposes for the knowledge base."""

    model_config = ConfigDict(extra="forbid")

    text: str = Field(min_length=20, max_length=800)
    topic: str = Field(min_length=2, max_length=60)        # "Testing", "Ghost movement"
    paths: list[str] = Field(default_factory=list, max_length=12)
    replaces: str | None = Field(default=None, pattern=r"^K[0-9]+$")


def _dir(data_root: Path, project_id: str) -> Path:
    return Path(data_root) / "projects" / project_id / "knowledge"


def _is_test(path: str) -> bool:
    name = path.rsplit("/", 1)[-1]
    return (path.startswith("tests/") or "/tests/" in path or "/__tests__/" in path
            or ".test." in name or ".spec." in name or name.startswith("test_"))


def _git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", f"--git-dir={repo}", *args], check=True, capture_output=True,
                          text=True).stdout


def build_facts(data_root: Path, project_id: str, *, ref: str = "main",
                check_command: str = "") -> dict[str, Any] | None:  # Any: JSON
    """Generate the facts layer from the project repo at `ref` and store it. None when the
    project has no repo yet."""
    repo = Path(data_root) / "projects" / project_id / "repo.git"
    if not repo.is_dir():
        return None
    try:
        files = [f for f in _git(repo, "ls-tree", "-r", "--name-only", ref).splitlines()
                 if f and not any(p in f + "/" for p in SKIP_PARTS)]
    except subprocess.CalledProcessError:
        return None                       # an empty repo has no `main` yet
    design = Design.load(data_root, project_id)
    modules, tests = [], []
    for path in files:
        if not path.endswith(CODE_SUFFIXES):
            continue
        if _is_test(path):
            tests.append(path)
            continue
        if len(modules) >= MAX_MODULES:
            continue
        try:
            text = _git(repo, "show", f"{ref}:{path}")
        except subprocess.CalledProcessError:
            continue
        owner = design.component_of(path)
        modules.append({"path": path, "lines": text.count("\n") + 1,
                        "exports": exported_names(path, text)[:20],
                        "component": owner.id if owner else None})
    facts = {"generated_at": time.time(), "ref": ref,
             "commit": _git(repo, "rev-parse", ref).strip(),
             "files": len(files), "modules": modules, "tests": tests,
             "test_map": _test_map(data_root, project_id),
             "commands": [c for c in [check_command.strip()] if c]}
    folder = _dir(data_root, project_id)
    folder.mkdir(parents=True, exist_ok=True)
    (folder / FACTS_FILE).write_text(json.dumps(facts, indent=1), encoding="utf-8")
    return facts


def _test_map(data_root: Path, project_id: str) -> dict[str, list[str]]:
    """check id → the tests that verified it in accepted sessions (newest wins)."""
    from core.project_repo import ProjectRepo
    out: dict[str, list[str]] = {}
    for run in reversed(ProjectRepo(data_root, project_id).runs()):     # oldest first
        if run.state != "accepted" or not isinstance(run.check, dict):
            continue
        for cid, entry in (run.check.get("ledger") or {}).items():
            if isinstance(entry, dict) and entry.get("state") == "verified" and entry.get("tests"):
                out[cid] = [str(t) for t in entry["tests"]]
    return out


def load_facts(data_root: Path | None, project_id: str | None) -> dict[str, Any] | None:  # Any: JSON
    """The stored facts, or None."""
    if data_root is None or not project_id:
        return None
    path = _dir(data_root, project_id) / FACTS_FILE
    try:
        data = json.loads(path.read_text(encoding="utf-8")) if path.is_file() else None
    except (OSError, ValueError):
        return None
    return data if isinstance(data, dict) else None


# ── notes ───────────────────────────────────────────────────────────────────
@dataclass(frozen=True)
class NoteChange:
    """What adding notes did."""

    added: list[str]
    replaced: list[str]


def add_notes(data_root: Path, project_id: str, notes: Sequence[KnowledgeNote], *, by: str,
              approve: bool, run_id: str | None = None) -> NoteChange:
    """Add notes (approved at once when `approve`, else proposed). A note that `replaces`
    another drops the old one."""
    added, replaced = [], []
    now = time.time()
    with WorkDB(Path(data_root) / "projects" / project_id).knowledge_doc() as rows:
        num = max([int(r["id"][1:]) for r in rows if str(r.get("id", "")).startswith("K")]
                  + [0])
        for note in notes:
            num += 1
            nid = f"K{num}"
            rows.append({"id": nid, "text": note.text.strip(), "topic": note.topic.strip(),
                         "paths": list(note.paths), "status": "approved" if approve else
                         "proposed", "by": by, "at": now, "run_id": run_id,
                         **({"approved_by": by} if approve else {}),
                         **({"replaces": note.replaces} if note.replaces else {})})
            added.append(nid)
            if note.replaces and approve:
                old = next((r for r in rows if r["id"] == note.replaces), None)
                if old is not None and old.get("status") != "dropped":
                    old.update(status="dropped", replaced_by=nid, at=now)
                    replaced.append(note.replaces)
    return NoteChange(added, replaced)


def decide_note(data_root: Path, project_id: str, note_id: str, *, approve: bool,
                by: str) -> dict[str, Any]:  # Any: JSON row
    """A person approves (or drops) a proposed or stale note. KeyError if unknown."""
    with WorkDB(Path(data_root) / "projects" / project_id).knowledge_doc() as rows:
        row = next((r for r in rows if r["id"] == note_id), None)
        if row is None:
            raise KeyError(note_id)
        row.update(status="approved" if approve else "dropped", approved_by=by, at=time.time())
        replaces = row.get("replaces")
        if approve and replaces:
            old = next((r for r in rows if r["id"] == replaces), None)
            if old is not None:
                old.update(status="dropped", replaced_by=note_id)
        return dict(row)


def mark_stale(data_root: Path, project_id: str, changed: Iterable[str], run_id: str) -> list[str]:
    """Approved notes about files an accepted session changed turn stale."""
    changed = [c for c in changed if c]
    stale = []
    with WorkDB(Path(data_root) / "projects" / project_id).knowledge_doc() as rows:
        for row in rows:
            if row.get("status") != "approved" or not row.get("paths"):
                continue
            if any(path_matches(c, p) or path_matches(p, c) for c in changed
                   for p in row["paths"]):
                row.update(status="stale", stale_since=run_id)
                stale.append(row["id"])
    return stale


def notes(data_root: Path | None, project_id: str | None,
          status: Iterable[NoteStatus] = ("approved",)) -> list[dict[str, Any]]:  # Any: JSON rows
    """Notes with one of `status`."""
    if data_root is None or not project_id:
        return []
    wanted = set(status)
    return [r for r in WorkDB(Path(data_root) / "projects" / project_id).read_knowledge()
            if r.get("status") in wanted]


# ── briefs ──────────────────────────────────────────────────────────────────
def _touches(note: Mapping[str, Any], files: Sequence[str]) -> bool:  # Any: JSON row
    paths = note.get("paths") or []
    if not paths:
        return True                       # a project-wide note applies everywhere
    return any(path_matches(f, p) or path_matches(p, f) for f in files for p in paths)


def render_for_brief(facts: Mapping[str, Any] | None, rows: Sequence[Mapping[str, Any]],  # Any: JSON
                     files: Sequence[str] = ()) -> str | None:
    """The "Project knowledge" section for a card (its files) or the whole project (no files).
    Facts are GuudFlow's own; notes only an agent approved are wrapped as untrusted."""
    parts: list[str] = []
    if facts:
        mods = [m for m in facts.get("modules", [])
                if not files or any(path_matches(m["path"], f) or path_matches(f, m["path"])
                                    for f in files)]
        if mods:
            lines = [f"- `{m['path']}` ({m['lines']} lines)"
                     + (f": {', '.join(m['exports'][:8])}" if m.get("exports") else "")
                     for m in mods[:MAX_FACT_LINES]]
            if len(mods) > MAX_FACT_LINES:
                lines.append(f"- … {len(mods) - MAX_FACT_LINES} more")
            parts.append("Modules on `main` (generated by GuudFlow):\n" + "\n".join(lines))
        if facts.get("commands"):
            parts.append("The check command: " + ", ".join(f"`{c}`" for c in facts["commands"]))
    picked = [r for r in rows if r.get("status") == "approved" and _touches(r, files)]
    trusted = [r for r in picked if r.get("approved_by") == "human"]
    agent = [r for r in picked if r.get("approved_by") != "human"]
    if trusted:
        parts.append("Notes (approved by a person):\n" + "\n".join(
            f"- **{r['id']}** {r['topic']}: {r['text']}" for r in trusted))
    if agent:
        parts.append(wrap_untrusted("knowledge notes approved by the tech lead", "\n".join(
            f"- {r['id']} {r['topic']}: {r['text']}" for r in agent)))
    if not parts:
        return None
    return ("What the team knows about this code. The code is the truth: when a note and the "
            "code disagree, trust the code and say so in your result.\n\n" + "\n\n".join(parts))


