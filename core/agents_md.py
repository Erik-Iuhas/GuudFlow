"""The project's own `AGENTS.md` (worker context plan R4).

On accept, GuudFlow writes `AGENTS.md` onto the project's `main` from the stack, the binding
rules, the check command and the knowledge notes a person approved. The code then explains
itself to any coding agent, inside GuudFlow or not.

A file GuudFlow wrote starts with `MARKER` and is rewritten on each accept. An `AGENTS.md`
without the marker belongs to a person and is never overwritten; its text reaches workers
through their rules file instead. Agents cannot change `AGENTS.md` (a protected path).
"""

from __future__ import annotations

import logging
import subprocess
from pathlib import Path

log = logging.getLogger(__name__)

FILE = "AGENTS.md"
MARKER = ("<!-- Generated by GuudFlow from the project's stack, rules and approved knowledge "
          "notes. Change those in Studio, not this file. -->")


def render(data_root: Path, project_id: str) -> str | None:
    """The generated `AGENTS.md`, or None when there is nothing worth writing."""
    from core.harness.spec_brief import SpecBrief
    from core.knowledge import load_facts, notes
    brief = SpecBrief.load(data_root, project_id)
    spec = brief.spec if brief is not None else None
    facts = load_facts(data_root, project_id) or {}
    parts: list[str] = []
    if spec is not None and not spec.stack.empty:
        parts.append("## Stack\n" + "\n".join(spec.stack.lines()))
    commands = [str(c) for c in facts.get("commands") or []]
    if commands:
        parts.append("## Checks\nRun before you finish: " + ", ".join(f"`{c}`" for c in commands))
    rules = [r for r in (spec.rules if spec is not None else [])
             if r.status == "active" and r.strength == "binding"]
    if rules:
        parts.append("## Rules\n" + "\n".join(f"- {r.text}" for r in rules))
    approved = [n for n in notes(data_root, project_id) if n.get("approved_by") == "human"]
    if approved:
        parts.append("## Notes\n" + "\n".join(f"- **{n.get('topic')}**: {n.get('text')}"
                                             for n in approved))
    if not parts:
        return None
    return f"{MARKER}\n# Working on this project\n\n" + "\n\n".join(parts) + "\n"


def main_text(repo_path: Path) -> str | None:
    """`AGENTS.md` on the bare project repo's `main`, or None."""
    proc = subprocess.run(["git", f"--git-dir={repo_path}", "show", f"main:{FILE}"],
                          capture_output=True, text=True)
    return proc.stdout if proc.returncode == 0 else None


def person_written(text: str | None) -> bool:
    """True for an `AGENTS.md` a person wrote (no GuudFlow marker)."""
    return bool(text and text.strip()) and not text.lstrip().startswith(MARKER)


def write(data_root: Path, project_id: str, why: str) -> str | None:
    """Commit the generated `AGENTS.md` onto main, unless a person owns the file. Never raises;
    returns the new main sha or None."""
    try:
        from core.project_repo import ProjectRepo
        repo = ProjectRepo(data_root, project_id)
        if not repo.exists() or person_written(main_text(repo.path)):
            return None
        text = render(data_root, project_id)
        if text is None:
            return None
        return repo.commit_files({FILE: text}, f"docs: update AGENTS.md {why}")
    except Exception:  # noqa: BLE001 — the accept has already happened
        log.exception("writing AGENTS.md %s failed", why)
        return None


__all__ = ["FILE", "MARKER", "main_text", "person_written", "render", "write"]
