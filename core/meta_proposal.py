# ── Parsing ────────────────────────────────────────────────────────────────


@dataclass
class ParseResult:
    """Output of `parse_proposal_args`: the structured proposal plus
    any warnings from sanitisation (e.g. role-name collisions
    auto-fixed)."""

    rationale: str
    agents: list[AgentConfig]
    rbac: dict[str, RoleRBAC]
    persona_hires: list[PersonaHire]
    warnings: list[str] = field(default_factory=list)
    # M2: project-overlay desk seeds. dict[persona_id → list[DeskFileSeed dict]].
    # Runner materializes these into the project overlay before the run starts.
    desk_seeds: dict[str, list[dict[str, Any]]] = field(default_factory=dict)
    # M1 §7b: story seeds for this run. Shape matches ProjectConfig.stories.
    stories: list[dict[str, Any]] = field(default_factory=list)


def parse_proposal_args(
    args: dict[str, Any],
    archetypes: list[ArchetypeMeta],
    roster: list[dict[str, Any]],
    *,
    harness: str = "legacy",
    model_registry: "ModelRegistry | None" = None,
    kind_team: list[str] | None = None,
) -> ParseResult:
    """Turn the LLM's `propose_team` tool-call arguments into a
    structured proposal. Defensive: missing or malformed fields are
    sanitised with warnings rather than failing outright. The caller
    (MetaAgent) decides whether to fall back to the skeleton based on
    how degraded the result is.

    Harness fields (plan §5.7, §4.5, §4.6) per agent: `role_type`,
    `capabilities` (partial overrides), `review_of`, `max_review_rounds`.
    `model_registry`, when given, is used to turn `vision` off for roles whose
    model cannot read images. With `harness="opencode"` a default `planner`
    role is added when the team has 2+ builders and no planner; the default
    ("legacy") never adds one. `kind_team` (the project kind's contract ids, role contracts
    plan §3) gives each proposed role the contract of its role type; when one of them owns the
    session plan (a tech lead) no default planner is added.
    """
    warnings: list[str] = []

    rationale = str(args.get("rationale") or "").strip()
    if not rationale:
        warnings.append("rationale was empty")

    raw_agents = args.get("agents") or []
    if not isinstance(raw_agents, list):
        return ParseResult(
            rationale=rationale,
            agents=[],
            rbac={},
            persona_hires=[],
            warnings=warnings + ["`agents` field was not a list"],
        )

    archetypes_by_name = {a.name: a for a in archetypes}
    existing_persona_ids: set[str] = {
        str(p.get("persona_id")) for p in roster if p.get("persona_id")
    }
    # Track display names used WITHIN this proposal so a 3-agent team
    # reads like 3 humans (Mike, Sarah, Alex) rather than 3 Mikes.
    # Populated as we walk roles: existing-hire's name + create_new's
    # generated name. NOT pre-populated with the full roster (that
    # would ban every persona name globally, defeating the point).
    used_display_names: set[str] = set()
    roster_by_id = {
        str(p.get("persona_id")): p for p in roster if p.get("persona_id")
    }

    role_names: list[str] = []
    raw_role_data: list[dict[str, Any]] = []
    raw_review_of: dict[str, Any] = {}
    for raw in raw_agents:
        if not isinstance(raw, dict):
            warnings.append("skipped a non-dict agent entry")
            continue
        role = str(raw.get("role") or "").strip()
        if not role:
            warnings.append("skipped agent with empty role")
            continue
        role_names.append(role)
        raw_role_data.append(raw)

    deduped = dedupe_role_names(role_names)
    if deduped != role_names:
        warnings.append("role name collisions were auto-renumbered")

    agents: list[AgentConfig] = []
    rbac: dict[str, RoleRBAC] = {}
    hires: list[PersonaHire] = []

    for role, raw in zip(deduped, raw_role_data):
        archetype_name = str(raw.get("archetype") or "").strip()
        archetype = archetypes_by_name.get(archetype_name)
        if archetype is None:
            warnings.append(
                f"role {role!r} referenced unknown archetype "
                f"{archetype_name!r}; defaulting to a generic specialist"
            )

        # Pull defaults from the archetype if found, else conservative.
        default_tools = list(archetype.default_tools) if archetype else ["fs-read"]
        default_rbac = list(archetype.default_rbac_scopes) if archetype else []
        default_tier = archetype.default_model_tier if archetype else "solid"

        # If the archetype is shipped (concrete class), use its registry
        # name so the runner's agent_factory builds the class. Else
        # leave agent_class_role_type=None for prompt-defined.
        agent_class_role_type: str | None = None
        if archetype is not None:
            from agents.registry import registry as _registry
            if _registry.has(archetype.name):
                agent_class_role_type = archetype.name

        # System prompt: for shipped, the class provides it. For
        # described-only, pull from the YAML.
        system_prompt = ""
        if agent_class_role_type is None and archetype is not None:
            doc_entry = get_doc_archetype(archetype.name)
            if doc_entry is not None:
                system_prompt = doc_entry.responsibility.strip()

        # Persona handling.
        persona_id: str | None = None
        persona_block = raw.get("persona") if isinstance(raw.get("persona"), dict) else None
        if persona_block is not None:
            action = str(persona_block.get("action") or "").strip()
            hire_goal = str(persona_block.get("goal") or "")[:120]
            if action == "hire_existing":
                pid = str(persona_block.get("persona_id") or "").strip()
                if pid in existing_persona_ids:
                    persona_id = pid
                    existing_persona = roster_by_id.get(pid, {})
                    display = str(existing_persona.get("name") or pid)
                    used_display_names.add(display)
                    hires.append(PersonaHire(
                        role=role, action="hire_existing",
                        persona_id=pid, display_name=display,
                        rationale=str(persona_block.get("rationale") or ""),
                        goal=hire_goal,
                    ))
                else:
                    warnings.append(
                        f"role {role!r} requested hire_existing for "
                        f"unknown persona {pid!r}; falling back to create_new"
                    )
                    action = "create_new"
            if action == "create_new":
                hint = str(persona_block.get("name_hint") or "").strip() or None
                pid, display = suggest_persona_id(
                    role=role,
                    existing_ids=existing_persona_ids,
                    name_hint=hint,
                    used_display_names=used_display_names,
                )
                persona_id = pid
                existing_persona_ids.add(pid)
                used_display_names.add(display)
                hires.append(PersonaHire(
                    role=role, action="create_new",
                    persona_id=pid, display_name=display,
                    rationale=str(persona_block.get("rationale") or ""),
                    goal=hire_goal,
                ))

        model_tier = str(raw.get("model_tier") or default_tier)
        is_reviewer = bool(raw.get("is_reviewer", False))
        role_type = _resolve_role_type(role, raw.get("role_type"), is_reviewer, warnings)
        capabilities = _resolve_capabilities(
            role, role_type, raw.get("capabilities"), model_tier, model_registry, warnings,
        )
        raw_review_of[role] = raw.get("review_of")

        agents.append(AgentConfig(
            role=role,
            description=str(raw.get("description") or "").strip(),
            depends_on=[str(d) for d in (raw.get("depends_on") or [])],
            system_prompt=system_prompt,
            declared_local_tools=default_tools,
            declared_mcp_servers=[],
            persona_id=persona_id,
            model_tier=model_tier,
            agent_class_role_type=agent_class_role_type,
            is_reviewer=is_reviewer,
            is_final_reviewer=bool(raw.get("is_final_reviewer", False)),
            persona_goal=hire_goal if persona_block is not None else "",
            manages=[str(r) for r in (raw.get("manages") or [])],
            escalates_to=[str(r) for r in (raw.get("escalates_to") or [])],
            role_type=role_type,
            capabilities=capabilities,
            max_review_rounds=_clamp_review_rounds(role, raw.get("max_review_rounds"), warnings),
        ))
        rbac[role] = RoleRBAC(role=role, allowed_scopes=default_rbac)

    # Sanity: an agent flagged is_final_reviewer must actually run last.
    # If something else depends on it (directly or transitively), the meta
    # mis-tagged it — strip the flag so the runner doesn't gate the run on
    # tick 0 awaiting approval for "validating finished work" that hasn't
    # happened. See core/runner.py:1173 for the gate.
    role_to_agent = {a.role: a for a in agents}
    has_dependent: dict[str, bool] = {a.role: False for a in agents}
    for a in agents:
        for dep in a.depends_on:
            if dep in has_dependent:
                has_dependent[dep] = True
    for a in agents:
        if a.is_final_reviewer and has_dependent.get(a.role, False):
            warnings.append(
                f"agent {a.role!r} was marked is_final_reviewer=true but "
                f"other agents depend on it; clearing the flag"
            )
            a.is_final_reviewer = False

    lead = _assign_contracts(agents, kind_team or [], warnings)
    # Planner (plan §4.6): opencode harness only, so legacy runs keep their shape.
    if harness == "opencode" and lead is None:
        _ensure_planner(agents, rbac, model_registry, warnings)

    # Review edges (plan §4.5), after the planner exists so defaults skip it.
    _resolve_review_edges(agents, raw_review_of, warnings)

    # M2: extract desk_seeds — dict[persona_id → list[DeskFileSeed dicts]]
    raw_desk_seeds = args.get("desk_seeds") or {}
    desk_seeds: dict[str, list[dict[str, Any]]] = {}
    if isinstance(raw_desk_seeds, dict):
        for persona_id_key, seed_list in raw_desk_seeds.items():
            if not isinstance(seed_list, list):
                continue
            valid_seeds = []
            for seed in seed_list:
                if not isinstance(seed, dict):
                    continue
                if not seed.get("name") or not seed.get("triggers") or not seed.get("body"):
                    warnings.append(f"desk_seeds: seed missing required fields for {persona_id_key!r} — skipped")
                    continue
                valid_seeds.append({
                    "name": str(seed["name"]).strip().lower().replace(" ", "-"),
                    "triggers": [str(t).strip().lower() for t in seed["triggers"] if str(t).strip()],
                    "body": str(seed["body"]),
                    "kind": str(seed.get("kind", "convention")),
                    "priority": str(seed.get("priority", "normal")),
                })
            if valid_seeds:
                desk_seeds[str(persona_id_key)] = valid_seeds

    # M1 §7b: extract story seeds.
    raw_stories = args.get("stories") or []
    stories: list[dict[str, Any]] = []
    valid_role_names = {a.role for a in agents}
    if isinstance(raw_stories, list):
        for s in raw_stories:
            if not isinstance(s, dict):
                continue
            name = str(s.get("name") or "").strip().lower().replace(" ", "-")
            goal = str(s.get("goal") or "").strip()
            if not name or not goal:
                warnings.append("story seed missing name or goal — skipped")
                continue
            owner = s.get("owner_role")
            if owner is not None:
                owner = str(owner).strip()
                if owner not in valid_role_names:
                    warnings.append(
                        f"story {name!r} owner_role {owner!r} not in proposed team — cleared"
                    )
                    owner = None
            stories.append({
                "name": name,
                "goal": goal,
                "owner_role": owner or None,
                "parent_story_id": None,
            })

    return ParseResult(
        rationale=rationale or "(meta-agent did not provide a rationale)",
        agents=agents,
        rbac=rbac,
        persona_hires=hires,
        warnings=warnings,
        desk_seeds=desk_seeds,
        stories=stories,
    )


# ── Harness fields (role type, capabilities, review edges, planner) ───────


def _resolve_role_type(
    role: str, declared: Any, is_reviewer: bool, warnings: list[str],
) -> str:
    """Role type from the proposal, else inferred. Invalid declarations warn."""
    text = str(declared or "").strip()
    if text and text not in ROLE_TYPES:
        warnings.append(
            f"role {role!r} declared unknown role_type {text!r}; inferring from the role name"
        )
        text = ""
    return infer_role_type(role, is_reviewer=is_reviewer, declared=text)


def _model_supports_images(registry: "ModelRegistry | None", tier: str) -> tuple[bool, str]:
    """(supports_images, model_id) for the model the tier resolves to.

    With no registry, or when the tier resolves to nothing, vision is not gated
    (returns True): the runner re-gates at spawn time anyway.
    """
    if registry is None:
        return True, ""
    try:
        info = registry.resolve(tier)
    except Exception as exc:  # NoModelAvailableError or a broken registry
        _logger.debug("vision gate skipped for tier %r: %s", tier, exc)
        return True, ""
    return bool(info.supports_images), str(info.id)


def _resolve_capabilities(
    role: str,
    role_type: str,
    raw_caps: Any,
    tier: str,
    registry: "ModelRegistry | None",
    warnings: list[str],
) -> dict[str, str]:
    """Validate a partial capability dict; returns the overrides to store.

    Each toggle is validated on its own (via `Capabilities.from_dict` on top of
    the role-type defaults), so one bad value is dropped with a warning and the
    rest survive. `sandbox: host_dev` is never accepted from a proposal. Vision
    is forced off (and recorded as an override) when the role's model cannot
    read images.
    """
    base = defaults_for(role_type)
    overrides: dict[str, str] = {}
    if raw_caps is not None and not isinstance(raw_caps, dict):
        warnings.append(f"role {role!r} capabilities was not an object; ignored")
        raw_caps = {}
    for key, value in (raw_caps or {}).items():
        try:
            Capabilities.from_dict({key: value}, base=base)
        except (CapabilityError, TypeError) as exc:
            warnings.append(f"role {role!r} capability dropped: {exc}")
            continue
        if key == "sandbox" and value == "host_dev":
            warnings.append(
                f"role {role!r} capability dropped: sandbox 'host_dev' cannot be "
                "proposed (a human may set it on the approval screen)"
            )
            continue
        overrides[str(key)] = str(value)

    effective = Capabilities.from_dict(overrides, base=base)
    supports, model_id = _model_supports_images(registry, tier)
    if gate_vision(effective, supports).vision != effective.vision:
        overrides["vision"] = "off"
        warnings.append(
            f"role {role!r}: vision turned off, model {model_id!r} has no image input"
        )
    return overrides


def _clamp_review_rounds(role: str, raw: Any, warnings: list[str]) -> int:
    """`max_review_rounds` clamped to 1..5; missing means the default (2)."""
    if raw is None:
        return DEFAULT_REVIEW_ROUNDS
    try:
        if isinstance(raw, bool):
            raise ValueError("bool")
        value = int(raw)
    except (TypeError, ValueError):
        warnings.append(
            f"role {role!r} max_review_rounds {raw!r} is not an integer; "
            f"using {DEFAULT_REVIEW_ROUNDS}"
        )
        return DEFAULT_REVIEW_ROUNDS
    clamped = max(MIN_REVIEW_ROUNDS, min(MAX_REVIEW_ROUNDS, value))
    if clamped != value:
        warnings.append(
            f"role {role!r} max_review_rounds {value} clamped to {clamped} "
            f"(allowed {MIN_REVIEW_ROUNDS}-{MAX_REVIEW_ROUNDS})"
        )
    return clamped


def _is_review_role(agent: AgentConfig) -> bool:
    """True for reviewers and the final reviewer (never counted as builders)."""
    return agent.is_reviewer or agent.is_final_reviewer or agent.role_type == "reviewer"


def _assign_contracts(agents: list[AgentConfig], kind_team: list[str],
                      warnings: list[str]) -> str | None:
    """Give proposed roles the kind's contracts by role type, in the kind's team order (role
    contracts plan §3). The role that now owns the session plan (a tech lead), if any, is
    returned, and the other non-reviewer roles depend on it as they would on a planner.
    Missing lead roles are warned."""
    if not kind_team:
        return None
    from core.contracts import load_library
    lib = load_library()
    plans: AgentConfig | None = None
    for cid in kind_team:
        contract = lib.get(cid)
        if contract is None or cid == "product_manager":
            continue
        row = next((a for a in agents if not a.contract and a.role_type == contract.role_type),
                   None)
        if row is None:
            if contract.may_change("session_plan") or contract.may_change("design"):
                warnings.append(f"the project kind expects a {contract.title} "
                                f"(role_type {contract.role_type}, contract {cid}); "
                                "none was proposed")
            continue
        row.contract = cid
        if plans is None and contract.may_change("session_plan"):
            plans = row
    if plans is None:
        return None
    for a in agents:
        if a is plans or _is_review_role(a) or a.role in plans.depends_on:
            continue
        if plans.role not in a.depends_on:
            a.depends_on.append(plans.role)
    return plans.role


def _ensure_planner(
    agents: list[AgentConfig],
    rbac: dict[str, RoleRBAC],
    registry: "ModelRegistry | None",
    warnings: list[str],
) -> None:
    """Add a default planner when the team has 2+ non-reviewer roles and no planner.

    The planner goes first, has no depends_on, and every other non-reviewer
    role gains it as a dependency. Records the addition in `warnings`.
    """
    workers = [a for a in agents if not _is_review_role(a)]
    if len(workers) < 2 or any(a.role_type == "planner" for a in agents):
        return
    taken = {a.role for a in agents}
    name = "planner"
    n = 1
    while name in taken:
        n += 1
        name = f"planner_{n}"
    planner = AgentConfig(
        role=name,
        description=(
            "Breaks the goal into a task list (owner, acceptance checklist, "
            "dependencies) that the other roles work from."
        ),
        depends_on=[],
        declared_local_tools=["fs-read", "fs-list", "git-diff", "git-log", "git-read"],
        declared_mcp_servers=[],
        model_tier="solid",
        role_type="planner",
    )
    # QUESTION: planner RBAC scopes are empty (conservative); the harness derives its
    # edit scope (docs/**) from role_type, not from these legacy scopes.
    planner.capabilities = _resolve_capabilities(
        name, "planner", None, planner.model_tier, registry, warnings,
    )
    for a in workers:
        if name not in a.depends_on:
            a.depends_on.append(name)
    agents.insert(0, planner)
    rbac[name] = RoleRBAC(role=name, allowed_scopes=[])
    warnings.append(
        f"planner role {name!r} added: the team has {len(workers)} non-reviewer roles "
        "and no planner; every other non-reviewer role now depends on it"
    )


def _resolve_review_edges(
    agents: list[AgentConfig], raw_review_of: dict[str, Any], warnings: list[str],
) -> None:
    """Fill `review_of` from the proposal (unknown roles dropped) or by default.

    A reviewer with no (valid) `review_of` reviews every non-reviewer,
    non-planner role it depends on, or all such roles when it has none.
    """
    known = {a.role for a in agents}
    builders = [a.role for a in agents if not _is_review_role(a) and a.role_type != "planner"]
    for agent in agents:
        raw = raw_review_of.get(agent.role)
        edges: list[str] = []
        if raw is not None and not isinstance(raw, list):
            warnings.append(f"role {agent.role!r} review_of was not a list; ignored")
            raw = None
        for name in raw or []:
            target = str(name).strip()
            if target == agent.role:
                warnings.append(f"role {agent.role!r} review_of itself; dropped")
            elif target not in known:
                warnings.append(
                    f"role {agent.role!r} review_of unknown role {target!r}; dropped"
                )
            elif target not in edges:
                edges.append(target)
        if not edges and agent.is_reviewer:
            edges = [d for d in agent.depends_on if d in builders] or list(builders)
        agent.review_of = edges


# ── Delta computation (Phase D.3 — continuation runs) ─────────────────────


def _agent_to_dict(agent: Any) -> dict[str, Any]:
    """Coerce an AgentConfig (or dict from a stored project) into a
    common dict shape so delta computation can compare both sides."""
    if isinstance(agent, dict):
        return agent
    return {
        "role": agent.role,
        "model_tier": agent.model_tier,
        "persona_id": agent.persona_id,
        "agent_class_role_type": agent.agent_class_role_type,
        "is_reviewer": agent.is_reviewer,
        "is_final_reviewer": agent.is_final_reviewer,
    }


def compute_deltas(
    prior_agents: list[Any],
    new_agents: list[Any],
) -> list[dict[str, Any]]:
    """Compute role-level deltas between the prior team and the
    proposed team for a continuation run.

    Returns a list of dicts, one per role. Action values:
      - `keep` — role exists in both, no meaningful change
      - `drop` — role in prior but not proposed
      - `add` — role in proposed but not prior
      - `swap_tier` — role in both, `model_tier` changed
      - `replace_persona` — role in both, `persona_id` changed
        (and at least one side had a persona)

    Both inputs accept dicts (the project's stored config shape) OR
    `AgentConfig` instances (the parsed-proposal shape) interchangeably.
    """
    prior_by_role: dict[str, dict[str, Any]] = {}
    for a in prior_agents:
        d = _agent_to_dict(a)
        if d.get("role"):
            prior_by_role[str(d["role"])] = d

    new_by_role: dict[str, dict[str, Any]] = {}
    for a in new_agents:
        d = _agent_to_dict(a)
        if d.get("role"):
            new_by_role[str(d["role"])] = d

    deltas: list[dict[str, Any]] = []

    # Roles in prior — keep / drop / swap_tier / replace_persona.
    # Stable ordering: walk prior roles in their original order, then
    # add new-only roles after.
    for role, prior in prior_by_role.items():
        if role not in new_by_role:
            deltas.append({
                "role": role,
                "action": "drop",
                "from_state": {"model_tier": prior.get("model_tier")},
            })
            continue
        new = new_by_role[role]
        prior_tier = prior.get("model_tier")
        new_tier = new.get("model_tier")
        prior_pid = prior.get("persona_id")
        new_pid = new.get("persona_id")

        if prior_tier and new_tier and prior_tier != new_tier:
            deltas.append({
                "role": role,
                "action": "swap_tier",
                "from_state": {"model_tier": prior_tier},
                "to_state": {"model_tier": new_tier},
            })
        elif (prior_pid or new_pid) and prior_pid != new_pid:
            deltas.append({
                "role": role,
                "action": "replace_persona",
                "from_state": {"persona_id": prior_pid},
                "to_state": {"persona_id": new_pid},
            })
        else:
            deltas.append({"role": role, "action": "keep"})

    for role, new in new_by_role.items():
        if role in prior_by_role:
            continue
        deltas.append({
            "role": role,
            "action": "add",
            "to_state": {
                "model_tier": new.get("model_tier"),
                "persona_id": new.get("persona_id"),
            },
        })

    return deltas


