# ── Reading project inputs ─────────────────────────────────────────────────


_EXCERPT_CHARS = 800
_TEXTY_SUFFIXES = {".md", ".txt", ".markdown", ".rst", ".json", ".yaml", ".yml"}


def read_meta_inputs(project_dir: Path, project_id: str, goal: str) -> MetaInputs:
    """Walk `project_dir/inputs/` and produce a structured summary the
    meta-agent's prompt builder consumes."""
    inputs_dir = Path(project_dir) / "inputs"
    inputs = MetaInputs(project_id=project_id, goal=goal)

    if not inputs_dir.is_dir():
        return inputs

    # M2 §6: read README.md index first if it exists (generated by runner at run start).
    readme_path = inputs_dir / "README.md"
    if readme_path.is_file():
        try:
            inputs.readme_index = readme_path.read_text(encoding="utf-8").strip()
        except OSError:
            pass

    # Uploads: enumerate with size + a short text excerpt for files we
    # can read cheaply. PDF/Word files don't get an excerpt at this
    # layer (the meta-agent reads filename + size and infers).
    uploads_dir = inputs_dir / "uploads"
    if uploads_dir.is_dir():
        for f in sorted(uploads_dir.iterdir()):
            if not f.is_file():
                continue
            size = f.stat().st_size
            excerpt = ""
            if f.suffix.lower() in _TEXTY_SUFFIXES and size < 100_000:
                try:
                    excerpt = f.read_text(encoding="utf-8")[:_EXCERPT_CHARS]
                except OSError:
                    excerpt = ""
            inputs.uploads.append(UploadInfo(
                filename=f.name, size=size, excerpt=excerpt,
            ))

    # Source repo metadata (sidecar from D-prime Chunk 2).
    src_meta = inputs_dir / "source_repo.meta.json"
    if src_meta.is_file():
        try:
            inputs.source_repo = json.loads(
                src_meta.read_text(encoding="utf-8"),
            )
        except (json.JSONDecodeError, OSError):
            pass

    # Prior runs attached to the project (D-prime Chunk 3).
    for entry in sorted(inputs_dir.iterdir()):
        if entry.is_file() and entry.name.startswith("from_run_") and entry.name.endswith(".meta.json"):
            try:
                inputs.prior_runs.append(
                    json.loads(entry.read_text(encoding="utf-8")),
                )
            except (json.JSONDecodeError, OSError):
                continue

    return inputs


def attach_continuation_context(
    inputs: MetaInputs,
    project_dir: Path,
    prior_run_id: str,
    prior_team_roles: list[str] | None = None,
) -> MetaInputs:
    """Populate `inputs.continuation` with the prior run's context.

    Reads `inputs/from_run_{id}/feedback.md` for any user feedback,
    plus the prior_runs metadata for status / completed_agents.
    `prior_team_roles` comes from the caller (the route layer reads
    the project's stored config to know what the prior team looked like).
    """
    prior_meta = next(
        (m for m in inputs.prior_runs if m.get("run_id") == prior_run_id),
        None,
    )
    if prior_meta is None:
        return inputs

    feedback_path = (
        Path(project_dir) / "inputs" / f"from_run_{prior_run_id}" / "feedback.md"
    )
    feedback = ""
    if feedback_path.is_file():
        try:
            feedback = feedback_path.read_text(encoding="utf-8").strip()
        except OSError:
            feedback = ""

    inputs.continuation = PriorRunContext(
        run_id=prior_run_id,
        status=str(prior_meta.get("status", "")),
        completed_agents=list(prior_meta.get("completed_agents") or []),
        feedback=feedback,
        prior_team_roles=list(prior_team_roles or []),
    )
    return inputs


# ── Prompt rendering ───────────────────────────────────────────────────────


def render_archetype_catalog(archetypes: list[ArchetypeMeta]) -> str:
    """Compact archetype list for the meta-agent's prompt. The full
    `responsibility` prose comes from the YAML for prompt-defined
    agents at construction time — at proposal time the LLM sees one
    line per archetype to keep the prompt cheap."""
    lines = ["Available archetypes (pick by `archetype` field):"]
    for m in archetypes:
        line = (
            f"- {m.name} ({m.abstract_base}, {m.default_model_tier} tier): "
            f"{m.description}"
        )
        if m.when_to_use:
            line += f" — When to use: {m.when_to_use}"
        lines.append(line)
    return "\n".join(lines)


def render_persona_roster(roster: list[dict[str, Any]]) -> str:
    """Compact persona list. Each entry: id, name, specialty, run count.
    The LLM uses this to pick `hire_existing` vs `create_new` per role."""
    if not roster:
        return "Persona roster is empty — every persona will be created new."
    lines = ["Available personas (use the `persona_id` for hire_existing):"]
    for p in roster:
        rep = p.get("reputation") or {}
        prod = rep.get("production") or {}
        runs = prod.get("total_runs", 0)
        lines.append(
            f"- {p.get('persona_id', '?')} ({p.get('name', '?')}, "
            f"{p.get('specialty', 'general')}): {runs} prior runs"
        )
    return "\n".join(lines)


def render_inputs(inputs: MetaInputs) -> str:
    """Render the project's inputs into a prompt block."""
    parts: list[str] = [f"Project goal: {inputs.goal}"]

    # M2 §6: show README index first so meta-agent has a structured view of inputs.
    if inputs.readme_index:
        parts.append("Input files index (from inputs/README.md):\n" + inputs.readme_index)

    if inputs.source_repo is not None:
        kind = inputs.source_repo.get("kind")
        if kind == "git_url":
            parts.append(
                f"Source repo: cloned from "
                f"{inputs.source_repo.get('git_url', '?')} @ "
                f"{inputs.source_repo.get('branch', 'main')}"
            )
        elif kind == "local_path":
            parts.append(
                f"Source repo: copied from local path "
                f"{inputs.source_repo.get('path', '?')}"
            )

    if inputs.uploads:
        parts.append("Uploaded inputs:")
        for u in inputs.uploads:
            line = f"  - uploads/{u.filename} ({u.size} bytes)"
            if u.excerpt:
                # Indent + cap the excerpt so the prompt stays compact.
                excerpt_short = u.excerpt[:200].replace("\n", " ")
                line += f" — excerpt: {excerpt_short}"
            parts.append(line)

    if inputs.continuation is not None:
        c = inputs.continuation
        parts.append(
            f"\nThis is a CONTINUATION of run {c.run_id} "
            f"(status={c.status}, completed: {', '.join(c.completed_agents) or '(none)'})."
        )
        if c.prior_team_roles:
            parts.append(f"Prior team roles: {', '.join(c.prior_team_roles)}")
        if c.feedback:
            parts.append(f"User feedback for this run:\n{c.feedback}")

    return "\n".join(parts)


def render_harness_guidance(harness: str = "legacy") -> str:
    """Prompt section describing role types, capability toggles, review edges
    and (opencode harness only) the planner role.

    Allowed capability values come from `core.harness.capabilities.LEVELS`.
    """
    lines = [
        "Per-role harness fields (all optional on each agent):",
        "- `role_type`: one of " + ", ".join(ROLE_TYPES) + ". It picks the role's "
        "default permissions; omit it and it is inferred from the role name.",
        "- `capabilities`: partial overrides of these toggles (allowed values in "
        "brackets). Omit a toggle to keep the role-type default. Grant only what "
        "the role needs; the human approves every toggle before the run.",
    ]
    for name, values in LEVELS.items():
        lines.append(f"    {name}: [{' | '.join(values)}]")
    lines += [
        "  `vision: on` is dropped automatically when the role's model cannot "
        "read images. `sandbox: host_dev` cannot be proposed.",
        "- `review_of`: for a reviewer, the roles whose work it reviews (a review "
        "edge: when the reviewer fails the work, those roles are re-run with the "
        "issues). Defaults to the non-reviewer roles it depends on. "
        f"`max_review_rounds` ({MIN_REVIEW_ROUNDS}-{MAX_REVIEW_ROUNDS}, default "
        f"{DEFAULT_REVIEW_ROUNDS}) caps the rework rounds before escalation.",
    ]
    if harness == "opencode":
        lines.append(
            "- Planner: a `planner` role (role_type planner) turns the goal into the "
            "task list the other roles work from. Include one when the team has 2 or "
            "more builders; it has no depends_on and every other non-reviewer role "
            "depends on it. If you omit it, GuudFlow adds a default planner."
        )
    return "\n".join(lines)


def render_playbook_section(playbook_text: str) -> str:
    """Delimited playbook section for the meta prompt; empty when there is none."""
    text = playbook_text.strip()
    if not text:
        return ""
    return (
        "=== Project playbook (lessons from earlier runs; propose changes, "
        "never apply silently) ===\n"
        f"{text}\n"
        "=== end project playbook ==="
    )


def render_backlog_section(backlog_text: str) -> str:
    """Delimited open-backlog section for the meta prompt (plan §13); empty when none."""
    text = backlog_text.strip()
    if not text:
        return ""
    return (
        "=== Project backlog (ongoing work the team will take on over the next runs; "
        "pick roles that can do it) ===\n"
        f"{text}\n"
        "=== end project backlog ==="
    )


def render_user_message(
    inputs: MetaInputs,
    archetypes: list[ArchetypeMeta],
    roster: list[dict[str, Any]],
    *,
    playbook_text: str = "",
    backlog_text: str = "",
    harness: str = "legacy",
) -> str:
    """Build the full user message the LLM sees.

    `playbook_text` (the project playbook rendered for the meta-agent) adds a
    delimited section only when non-empty. `harness` ("legacy" | "opencode")
    controls whether the planner role is described.
    """
    is_continuation = inputs.continuation is not None
    if is_continuation and inputs.continuation and inputs.continuation.feedback:
        story_instruction = (
            "Also populate `stories` in the tool call: extract one story per "
            "distinct theme from the user feedback above (e.g. 'auth-flow', "
            "'dashboard-ui', 'bug-fixes'). Each story gets a slug `name` and a "
            "one-sentence `goal`. Assign `owner_role` when a story belongs to a "
            "specific role; omit for shared work. 2-4 stories maximum."
        )
    else:
        story_instruction = (
            "If the goal has 2+ natural phases (e.g. backend + frontend, or "
            "design + implementation), populate `stories` with one slug per phase "
            "(e.g. 'backend-api', 'frontend-ui'). Omit for single-phase goals."
        )
    sections = [
        render_inputs(inputs),
        render_archetype_catalog(archetypes),
        render_persona_roster(roster),
        render_playbook_section(playbook_text),
        render_backlog_section(backlog_text),
        render_harness_guidance(harness),
        (
            "Propose a team using the `propose_team` tool. Ensure every "
            "role name is unique. Prefer descriptive role names "
            "(`auth_dev`, `api_dev`) over numeric suffixes. For each "
            "role, recommend either `hire_existing` (referencing a "
            "persona_id from the roster above) or `create_new` (with a "
            "name_hint like 'Mike' or 'Sarah' that fits the persona's "
            f"character). {story_instruction}"
        ),
    ]
    return "\n\n".join(sec for sec in sections if sec)


